/* Generates the static glossary markup inside glossary.html from
   assets/js/data-glossary.js, between the GLOSSARY:START / GLOSSARY:END
   markers.

   ── WHY THIS EXISTS ─────────────────────────────────────────
   The glossary was originally rendered from the data model in the
   browser. That cost 0.40 of cumulative layout shift on every load —
   four times the threshold Google calls "good" — because the entire
   body of the page arrived after first paint. It also meant any crawler
   that does not execute JavaScript saw a page with no terms on it, on
   one of the two pages whose whole purpose is being found.

   Pre-rendering fixes both without introducing a deploy-time build
   step: the generated HTML is committed, so the site stays a pile of
   static files. The data model remains the single source of truth and
   `--check` fails CI if the committed HTML has drifted from it.

   Usage:
     node scripts/build-glossary.mjs           # rewrite glossary.html
     node scripts/build-glossary.mjs --check   # exit 1 if out of date
*/
import { readFileSync, writeFileSync } from "node:fs";

const ROOT = new URL("..", import.meta.url);
const load = (file, name) => {
  const src = readFileSync(new URL(`assets/js/${file}`, ROOT), "utf8");
  return new Function(`${src}; return ${name};`)();
};
const JKG = load("data-glossary.js", "JKG");
const JKV = load("data-ventures.js", "JKV");

const esc = s => String(s == null ? "" : s)
  .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
  .replace(/"/g, "&quot;").replace(/'/g, "&#39;");

const slug = t => "t-" + t.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

/* Mirrors citeChip() in common.js. Duplicated deliberately and kept
   small: this runs in Node with no DOM, and importing the browser
   helper would drag the whole module in for four lines of markup. */
function citeChip(key) {
  const c = JKV.cites[key];
  if (!c) return "";
  const cls = c.s === "verified" ? "cite" : "cite unverified";
  const inner = c.url
    ? `<a href="${esc(c.url)}" target="_blank" rel="noopener noreferrer">${esc(c.ref)}</a>`
    : esc(c.ref);
  return `<span class="${cls}" title="${esc(c.long)}">${inner}</span>`;
}

function termHtml(t) {
  const see = (t.see || []).length
    ? `\n          <div class="see"><span>See also</span>${(t.see).map(s =>
        `<a href="#${slug(s)}" data-jump="${esc(s)}">${esc(s)}</a>`).join("")}</div>`
    : "";
  return `        <article class="g-term" id="${slug(t.t)}" data-cat="${esc(t.cat)}" data-term="${esc(t.t.toLowerCase())}">
          <h3>${esc(t.t)}${t.full ? ` <span class="full">${esc(t.full)}</span>` : ""}${t.cite ? citeChip(t.cite) : ""}</h3>
          <p>${esc(t.d)}</p>${t.why ? `\n          <div class="why"><b>Why it matters</b>${esc(t.why)}</div>` : ""}${see}
        </article>`;
}

const alpha = (a, b) => a.t.localeCompare(b.t, "en", { sensitivity: "base" });

const html = JKG.cats.map(c => {
  const items = JKG.byCat(c.id).slice().sort(alpha);
  return `      <div class="g-group" id="cat-${esc(c.id)}" data-cat="${esc(c.id)}">
        <h2><span aria-hidden="true">${c.icon}</span> ${esc(c.label)}
          <span class="muted g-n" style="font-size:.9rem;font-family:var(--sans);font-weight:400">${items.length}</span></h2>
        <p class="muted">${esc(c.blurb)}</p>
${items.map(termHtml).join("\n")}
      </div>`;
}).join("\n");

/* The filter chips and the A–Z rail are generated too. Building them in
   the browser was the last 0.16 of layout shift on this page: they sit
   above the term list, so inserting them at load pushed everything below
   them down. */
const catsHtml = [{ id: "all", label: "All", icon: "" }].concat(JKG.cats).map(c =>
  `        <button type="button" class="seg" data-c="${esc(c.id)}" aria-pressed="${c.id === "all"}">${c.icon ? c.icon + " " : ""}${esc(c.label)}</button>`).join("\n");

const firstFor = {};
JKG.terms.slice().sort(alpha).forEach(t => {
  const L = t.t[0].toUpperCase();
  if (!firstFor[L]) firstFor[L] = slug(t.t);
});
const lettersHtml = "ABCDEFGHIJKLMNOPQRSTUVWXYZ".split("").map(L =>
  firstFor[L] ? `<a href="#${firstFor[L]}">${L}</a>` : `<span aria-hidden="true">${L}</span>`).join("");

const START = "<!-- GLOSSARY:START — generated by scripts/build-glossary.mjs; do not edit by hand -->";
const END = "<!-- GLOSSARY:END -->";
const CSTART = "<!-- GLOSSARY:CATS -->", CEND = "<!-- /GLOSSARY:CATS -->";
const LSTART = "<!-- GLOSSARY:LETTERS -->", LEND = "<!-- /GLOSSARY:LETTERS -->";

const path = new URL("glossary.html", ROOT);
const src = readFileSync(path, "utf8");
const i = src.indexOf(START), j = src.indexOf(END);
if (i < 0 || j < 0) {
  console.error("FAIL: glossary.html is missing the GLOSSARY:START / GLOSSARY:END markers");
  process.exit(1);
}
let next = src.slice(0, i + START.length) + "\n" + html + "\n      " + src.slice(j);

for (const [open, close, block] of [[CSTART, CEND, catsHtml], [LSTART, LEND, lettersHtml]]) {
  const a = next.indexOf(open), b = next.indexOf(close);
  if (a < 0 || b < 0) { console.error(`FAIL: glossary.html is missing the ${open} markers`); process.exit(1); }
  const pad = block.includes("\n") ? "\n" : "";
  next = next.slice(0, a + open.length) + pad + block + pad + (pad ? "      " : "") + next.slice(b);
}

if (process.argv.includes("--check")) {
  if (next !== src) {
    console.error("FAIL: glossary.html is out of date with assets/js/data-glossary.js");
    console.error("      run: node scripts/build-glossary.mjs");
    process.exit(1);
  }
  console.log(`glossary.html is in sync — ${JKG.terms.length} terms across ${JKG.cats.length} categories`);
} else {
  writeFileSync(path, next);
  console.log(`glossary.html rebuilt — ${JKG.terms.length} terms across ${JKG.cats.length} categories`);
}
