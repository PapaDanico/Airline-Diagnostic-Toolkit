/* Collect what the suites verified into one committed file.
   Generated — edit the suites, not assets/verification.json.

   Run bare to regenerate. Run with --check to assert the committed file
   matches the run that just happened, which is what CI does.

   ── Why a committed file rather than a CI artifact ──

   The site has no build step: Netlify publishes the repository as-is.
   So anything a page reads has to be in the repository, and the only
   honest way to put a generated file there is the pattern this repo
   already uses for the glossary — commit it, and have CI regenerate and
   compare. If the two disagree the build fails, which means the
   committed figures cannot drift from the suites that produce them.

   ── What makes the published claim safe ──

   Three refusals, in order:

     A suite that did not run has no record, and a missing record stops
     publication. You cannot claim a check you skipped.

     A suite that failed writes passed:false, and any false stops
     publication. A red run cannot be published as a green one.

     A figure typed into the committed file by hand does not match the
     records, and --check fails. The numbers can only come from a run.

   No timestamp is stored, deliberately. A "last verified" date in a
   committed file is stale the moment anything else is committed, and
   this project has spent long enough removing figures that were true
   when written. What CI can honestly guarantee is that these numbers
   describe the commit being served — so the page says the checks run on
   every deploy, which is a claim the workflow makes true. */

import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const RECORDS = join(ROOT, "tests", ".verification");
const OUT = join(ROOT, "assets", "verification.json");
const check = process.argv.includes("--check");

/* Every suite that must have run before anything is published. Adding a
   suite here without hooking it makes the build fail, which is the
   right way round: the list is the claim, and the records are the
   evidence for it. */
const EXPECTED = ["e2e", "audit", "focus", "csp", "offline", "storage", "drive"];

if (!existsSync(RECORDS)) {
  console.error("❌ no verification records — run the test suites first (npm test)");
  process.exit(1);
}

const found = new Map();
for (const f of readdirSync(RECORDS)) {
  if (!f.endsWith(".json")) continue;
  const rec = JSON.parse(readFileSync(join(RECORDS, f), "utf8"));
  found.set(rec.suite, rec);
}

const missing = EXPECTED.filter((s) => !found.has(s));
if (missing.length) {
  console.error(`❌ these suites left no record, so nothing can be published: ${missing.join(", ")}`);
  console.error("   A verification claim covers the suites that ran, not the suites that exist.");
  process.exit(1);
}

const red = EXPECTED.filter((s) => found.get(s).passed !== true);
if (red.length) {
  console.error(`❌ these suites did not pass: ${red.join(", ")} — a red run is not published`);
  process.exit(1);
}

/* Stable order and shape, so the committed file only changes when a
   figure changes rather than when a directory listing does. */
const report = {
  note: "Generated by scripts/build-verification.mjs from the test suites. Do not edit.",
  suites: EXPECTED.map((s) => {
    const { suite, passed, headline, ...counts } = found.get(s);
    return { suite, headline, ...counts };
  })
};

const serialised = JSON.stringify(report, null, 2) + "\n";

if (check) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== serialised) {
    console.error("❌ assets/verification.json does not match the run that just happened.");
    console.error("   Regenerate it with `node scripts/build-verification.mjs` and commit the result.");
    process.exit(1);
  }
  console.log(`✅ verification report matches the run (${EXPECTED.length} suites)`);
  process.exit(0);
}

writeFileSync(OUT, serialised);
console.log(`✅ assets/verification.json written from ${EXPECTED.length} suite records`);
for (const s of report.suites) console.log(`     ${s.suite.padEnd(9)} ${s.headline}`);
